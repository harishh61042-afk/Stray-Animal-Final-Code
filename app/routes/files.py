"""Serving uploaded files.

Animal photos are public. Medical documents and verification documents are private: only people who may see
the record (or the document's owner / an administrator) can download them. File names are generated by the
server (uuid) and resolved with a path-traversal safe helper.
"""
from flask import Blueprint, abort, send_file
from flask_login import current_user

from app import constants as C
from app.extensions import db
from app.models import MedicalRecord, User
from app.services import medical_service, uploads
from app.utils.permissions import login_required

bp = Blueprint("files", __name__)

PUBLIC_CATEGORIES = (C.UPLOAD_ANIMALS, C.UPLOAD_ANIMAL_REPORTS)


def _send_private(path, name):
    response = send_file(path, conditional=True, download_name=name)
    response.headers["Cache-Control"] = "private, no-store"
    response.headers["X-Content-Type-Options"] = "nosniff"
    return response


@bp.route("/uploads/<category>/<path:filename>")
def uploaded(category, filename):
    if category not in PUBLIC_CATEGORIES:
        abort(404)
    path = uploads.resolve_upload(category, filename)
    if path is None:
        abort(404)
    response = send_file(path, conditional=True, max_age=86400)
    response.headers["X-Content-Type-Options"] = "nosniff"
    return response


@bp.route("/files/medical/<int:record_id>")
@login_required
def medical_document(record_id):
    record = db.get_or_404(MedicalRecord, record_id)
    if not medical_service.can_view_medical(current_user, record.animal):
        abort(403)
    path = uploads.resolve_upload(C.UPLOAD_MEDICAL, record.document_filename)
    if path is None:
        abort(404)
    return _send_private(path, record.document_original_name or record.document_filename)


@bp.route("/files/verification/<int:user_id>")
@login_required
def verification_document(user_id):
    if current_user.id != user_id and current_user.role != C.ROLE_ADMIN:
        abort(403)
    owner = db.get_or_404(User, user_id)
    profile = owner.role_profile
    filename = getattr(profile, "verification_document", None)
    path = uploads.resolve_upload(C.UPLOAD_VERIFICATION, filename)
    if path is None:
        abort(404)
    return _send_private(path, filename)
